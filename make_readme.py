import json
from pathlib import Path

with open('assets/benchmarks/benchmark_summary.json') as f:
    benchmarks = json.load(f)

# Group by category
categories = {}
for b in benchmarks:
    cat = b['category']
    if cat not in categories:
        categories[cat] = []
    categories[cat].append(b)

RAW_BASE = 'https://raw.githubusercontent.com/ProfLear/mirage/main/assets/benchmarks'

md = []
md.append('# Mirage 🪄')
md.append('')
md.append('> **Ultra-lightweight, browser-less static image exporter for Plotly in Python.**  ')
md.append('> *Zero Chrome. Zero Chromium. Zero Playwright. 100% Vector & Raster Fidelity.*')
md.append('')
md.append('---')
md.append('')
md.append('## Why Mirage?')
md.append('')
md.append('Historically, exporting static images (`.svg`, `.png`, `.jpg`, `.webp`) from Plotly in Python required **Kaleido**:')
md.append('* **Kaleido v0.1/v0.2** bundled an unmaintained, monolithic Chromium binary that frequently deadlocked, crashed on ARM64 / Apple Silicon, or failed on modern Linux distributions.')
md.append('* **Kaleido v1+** transitioned to requiring a full installation of Google Chrome or downloading ~150MB–300MB Playwright browser binaries.')
md.append('* In **Docker containers, AWS Lambda, lightweight Linux (Alpine), and CI/CD pipelines**, installing Chrome pulls in hundreds of megabytes of system packages (`libglib`, `libgtk`, `libnss`, `Xvfb`), making deployments bloated and fragile.')
md.append('')
md.append('**Mirage eliminates all browser dependencies entirely.** It executes Plotly\'s official SVG engine inside an embedded QuickJS JavaScript runtime, measures fonts using Pillow, and rasterizes pixel-perfect images via high-performance Rust (`resvg-py`).')
md.append('')
md.append('---')
md.append('')
md.append('## How Mirage Works')
md.append('')
md.append('Plotly Python figures are JSON specifications. The actual layout math, coordinate scaling, D3 curves, and SVG construction live inside `plotly.js`.')
md.append('')
md.append('```')
md.append('┌───────────────────────────────┐')
md.append('│     fig = go.Figure(...)      │')
md.append('└──────────────┬────────────────┘')
md.append('               │ fig.to_dict()')
md.append('               ▼')
md.append('┌────────────────────────────────────────────────────────┐')
md.append('│  Mirage Engine (Embedded QuickJS Runtime)               │')
md.append('│                                                        │')
md.append('│  1. Micro-DOM (~400 lines JS):                         │')
md.append('│     - Minimal SVG/HTML element tree                    │')
md.append('│     - D3 selector & attribute managers                 │')
md.append('│  2. Pillow Font Engine:                                │')
md.append('│     - Answers getBBox() text measurements via PIL      │')
md.append('│  3. Comprehensive 2D Plotly Engine:                    │')
md.append('│     - Computes layout & renders 29 pure-vector traces  │')
md.append('│  4. Extracts clean, standalone <svg>                   │')
md.append('└──────────────────────────────┬─────────────────────────┘')
md.append('                               │ Pure SVG Vector Output')
md.append('                               ▼')
md.append('                ┌───────────────────────────────┐')
md.append('                │    resvg-py (Rust Wheel)      │')
md.append('                │    Instant SVG ➔ PNG / JPEG   │')
md.append('                └───────────────────────────────┘')
md.append('```')
md.append('')
md.append('1. **Embedded QuickJS Engine**: Runs the official `plotly.js` bundle inside an embedded C JavaScript runtime (~1.8 MB bundle).')
md.append('2. **Micro-DOM**: Implements the precise subset of DOM and SVG APIs that D3 and Plotly require to build the SVG scene graph.')
md.append('3. **Pillow Font Engine**: When Plotly asks for text bounding boxes (`getBBox()`), Mirage queries Python\'s `PIL.ImageFont` to measure text dimensions, ensuring clean margins, titles, and tick placements without overlaps.')
md.append('4. **Rust Vector Rasterization (`resvg-py`)**: Converts SVG directly into crisp PNG, JPEG, or WEBP bytes in milliseconds with zero C++ system dependencies.')
md.append('')
